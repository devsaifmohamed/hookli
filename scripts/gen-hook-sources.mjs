// Generates apps/docs/lib/hook-sources.generated.ts from the library's real source
// files (packages/hookli/src/hooks/<slug>/<slug>.ts), plus each hook's direct
// dependencies on sibling hooks. The docs "Source" section, the per-hook AI
// markdown (llms.txt) and the StackBlitz playground all read from it, so they
// always show the code that actually ships.
//
//   node scripts/gen-hook-sources.mjs       (CI fails if the committed file is stale)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const manifest = JSON.parse(fs.readFileSync(path.join(root, "packages/hookli/hooks.manifest.json"), "utf8"));
const outPath = path.join(root, "apps/docs/lib/hook-sources.generated.ts");

const entries = {};
const problems = [];
for (const { slug } of manifest.hooks) {
  const rel = `packages/hookli/src/hooks/${slug}/${slug}.ts`;
  const file = path.join(root, rel);
  if (!fs.existsSync(file)) {
    problems.push(`${slug}: missing ${rel}`);
    continue;
  }
  const source = fs.readFileSync(file, "utf8");
  const deps = [...source.matchAll(/from\s+"\.\.\/(use-[a-z0-9-]+)"/g)].map((m) => m[1]);
  const foreign = [...source.matchAll(/from\s+"([^"]+)"/g)]
    .map((m) => m[1])
    .filter((spec) => spec !== "react" && !/^\.\.\/use-[a-z0-9-]+$/.test(spec));
  if (foreign.length) problems.push(`${slug}: unsupported import(s) ${foreign.join(", ")}`);
  entries[slug] = { path: rel, source, deps: [...new Set(deps)] };
}

if (problems.length) {
  console.error("gen-hook-sources: cannot generate\n  " + problems.join("\n  "));
  process.exit(1);
}

const body = [
  "/* GENERATED by scripts/gen-hook-sources.mjs from packages/hookli/src — do not edit.",
  "   Regenerate with `node scripts/gen-hook-sources.mjs`; CI fails when this is stale. */",
  "",
  "export type GeneratedHookSource = {",
  "  /* Repo-relative path of the hook file. */",
  "  path: string;",
  "  source: string;",
  "  /* Slugs of sibling hooks this hook imports (`../use-x`). */",
  "  deps: readonly string[];",
  "};",
  "",
  `export const GENERATED_HOOK_SOURCES: Readonly<Record<string, GeneratedHookSource>> = ${JSON.stringify(entries, null, 2)};`,
  "",
].join("\n");

fs.writeFileSync(outPath, body, "utf8");
console.log(`hook sources: ${Object.keys(entries).length} hooks -> ${path.relative(root, outPath)}`);
